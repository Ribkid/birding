// Writes supabase/migrations/20261026000100_species_kinds.sql from the dex: birds are ids 1–181,
// everything else comes from data/species-new.json. Re-run (and re-apply the file) when species are added.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const extra = JSON.parse(readFileSync(new URL('data/species-new.json', root), 'utf8'));
const rows = [];
for (let i = 1; i <= 181; i++) rows.push([i, 'bird']);
for (const x of extra) if (x && x.id > 181 && x.kind) rows.push([x.id, x.kind]);
const sql = `-- Species id -> kind, used by get_leaderboard() for per-kind counts. Generated by scripts/species-kinds-sql.mjs.
insert into public.species_kinds (species_id, kind) values
${rows.map(([id, k]) => `  (${id}, '${k}')`).join(',\n')}
on conflict (species_id) do update set kind = excluded.kind;
`;
writeFileSync(new URL('supabase/migrations/20261026000100_species_kinds.sql', root), sql);
console.log(`${rows.length} species`);
